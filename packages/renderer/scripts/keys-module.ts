// Renders src/keys.ts from the public keys in keys/*.pub.pem (renderer slice 3,
// commit 4). Shared by scripts/gen-keys.ts (writes the file) and
// test/keys.test.ts (fails when the file and the .pem files drift).
//
// Why a generated module rather than reading the .pem files at run time: the
// design tool's Next standalone build traces imported modules, not arbitrary
// files beside them, so a runtime readFileSync of keys/*.pem would depend on a
// path that may not exist inside the image. A string constant travels with
// the code.

import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";

export const KEYS_DIR = join(import.meta.dir, "..", "keys");
export const KEYS_MODULE = join(import.meta.dir, "..", "src", "keys.ts");

export type NamedKey = { name: string; pem: string };

/** Every keys/*.pub.pem, sorted by file name. Public halves only. */
export function readPublicKeys(dir: string = KEYS_DIR): NamedKey[] {
  return readdirSync(dir)
    .filter((f) => f.endsWith(".pub.pem"))
    .sort()
    .map((f) => ({
      name: f.slice(0, -".pub.pem".length),
      pem: readFileSync(join(dir, f), "utf8"),
    }));
}

export function renderKeysModule(keys: NamedKey[]): string {
  if (keys.length === 0) throw new Error("no keys/*.pub.pem found");
  for (const k of keys) {
    if (k.pem.includes("PRIVATE KEY")) {
      throw new Error(`keys/${k.name}.pub.pem carries a PRIVATE key — never commit one`);
    }
    if (!k.pem.includes("-----BEGIN PUBLIC KEY-----")) {
      throw new Error(`keys/${k.name}.pub.pem is not a PEM public key`);
    }
  }
  const entries = keys
    .map((k) => `  ${JSON.stringify(k.name)}: ${JSON.stringify(k.pem)},`)
    .join("\n");
  return `// GENERATED by scripts/gen-keys.ts from keys/*.pub.pem — do not edit.
// Regenerate with \`bun run keys\` (packages/renderer) after adding or
// replacing a public key; test/keys.test.ts fails while the two drift.
//
// The renderer manifest's trusted PUBLIC keys
// (docs/server-delivered-renderer-design.md 2.a): the working key (Secure
// Enclave) and, once IT sends it, the backup.

export const RENDERER_PUBLIC_KEYS_BY_NAME: Readonly<Record<string, string>> = {
${entries}
};

export const RENDERER_PUBLIC_KEYS: readonly string[] = Object.values(
  RENDERER_PUBLIC_KEYS_BY_NAME,
);
`;
}
